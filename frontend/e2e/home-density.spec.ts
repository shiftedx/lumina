import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { expect, test } from '@playwright/test';
import { episodeSummary } from '../src/test/galleryFixtures';
import { continueEntry, homeMovie, liveEntry, mockHome } from './home-mock';
import { mockApi, signIn } from './lumina-mock';

const OUT = join(process.cwd(), '..', 'output', 'home-density');
test('Home shelves fit the wide layout and preserve phone navigation', async ({ page }) => {
  await page.setViewportSize({ width: 2048, height: 1100 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  mkdirSync(OUT, { recursive: true });
  await mockApi(page, {});
  const episodes = Array.from({ length: 14 }, (_, index) => episodeSummary(2, index + 1));
  await mockHome(page, { artwork: true, continueWatching: episodes.map((entry) => continueEntry(entry)), nextUp: episodes, newest: Array.from({ length: 16 }, (_, index) => homeMovie(index)), live: { items: Array.from({ length: 12 }, (_, index) => liveEntry(`stream-${index}`)) } });
  await page.goto('/');
  await signIn(page);
  const hero = page.locator('.h-hero');
  const first = page.getByRole('region', { name: 'Continue watching' });
  const next = page.getByRole('region', { name: 'Next up' });
  const live = page.getByRole('region', { name: 'Live now' });
  const posters = page.getByRole('region', { name: 'New in your library' });
  await expect(first.locator('.h-card')).toHaveCount(14);
  await expect(next.locator('.h-card')).toHaveCount(14);
  await live.scrollIntoViewIfNeeded();
  await expect(live.locator('.h-card')).toHaveCount(12);
  await posters.scrollIntoViewIfNeeded();
  await expect(posters.locator('.h-card')).toHaveCount(16);
  const rect = (selector: string) => page.locator(selector).first().evaluate((node) => { const r = node.getBoundingClientRect(); return { top: r.top, bottom: r.bottom, width: r.width }; });
  expect((await rect('[data-shelf-section="continue"] .h-card')).width).toBeLessThanOrEqual(320);
  expect((await rect('[data-shelf-section="new_in_library"] .h-card')).width).toBeLessThanOrEqual(180);
  for (const section of [first, next, live, posters]) {
    const head = (await section.locator('.h-shelf-head').boundingBox())!;
    const card = (await section.locator('.h-card').first().boundingBox())!;
    expect(card.y - (head.y + head.height)).toBeLessThanOrEqual(52);
  }
  const firstHead = (await first.locator('.h-shelf-head').boundingBox())!;
  const heroBox = (await hero.boundingBox())!;
  expect(firstHead.y - (heroBox.y + heroBox.height)).toBeGreaterThanOrEqual(12);
  expect(firstHead.y - (heroBox.y + heroBox.height)).toBeLessThanOrEqual(16);
  for (const [previous, following] of [[first, next], [next, live], [live, posters]] as const) {
    const card = (await previous.locator('.h-card').first().boundingBox())!;
    const head = (await following.locator('.h-shelf-head').boundingBox())!;
    expect(head.y - (card.y + card.height)).toBeLessThanOrEqual(48);
  }
  await first.scrollIntoViewIfNeeded();
  const row = first.locator('.h-row');
  await first.getByRole('button', { name: 'Scroll Continue watching right' }).click();
  await expect.poll(() => row.evaluate((node) => node.scrollLeft)).toBeGreaterThan(0);
  const firstCard = first.locator('.h-card [data-focus-item]').first();
  await firstCard.focus();
  await page.keyboard.press('ArrowRight');
  await expect(firstCard).not.toBeFocused();
  await page.screenshot({ path: join(OUT, 'wide-2048.png') });
  await first.evaluate((element) => element.scrollIntoView({ block: 'start' }));
  await page.evaluate(() => window.scrollBy(0, -80));
  await page.waitForTimeout(250);
  await page.screenshot({ path: join(OUT, 'shelves-2048.png') });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.screenshot({ path: join(OUT, 'desktop-1440.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await first.scrollIntoViewIfNeeded();
  const phoneHead = (await first.locator('.h-shelf-head').boundingBox())!;
  const phoneHero = (await hero.boundingBox())!;
  expect(phoneHead.y - (phoneHero.y + phoneHero.height)).toBeGreaterThanOrEqual(12);
  expect(phoneHead.y - (phoneHero.y + phoneHero.height)).toBeLessThanOrEqual(16);
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
  const browse = page.getByRole('navigation', { name: 'Mobile primary navigation' }).getByRole('button', { name: 'Browse' });
  const browseBox = (await browse.boundingBox())!;
  expect(Math.min(browseBox.width, browseBox.height)).toBeGreaterThanOrEqual(44);
  const cardButton = first.locator('.h-card [data-focus-item]').first();
  const cardBox = (await cardButton.boundingBox())!;
  expect(Math.min(cardBox.width, cardBox.height)).toBeGreaterThanOrEqual(44);
  const caption = first.locator('.h-card .g-still-title').first();
  await expect(caption).toBeVisible();
  expect(await caption.evaluate((node) => parseFloat(getComputedStyle(node).fontSize))).toBeGreaterThanOrEqual(12);
  await page.screenshot({ path: join(OUT, 'phone-390.png') });
  await first.evaluate((element) => element.scrollIntoView({ block: 'start' }));
  await page.evaluate(() => window.scrollBy(0, -70));
  await page.waitForTimeout(250);
  await page.screenshot({ path: join(OUT, 'shelves-phone.png') });
});
