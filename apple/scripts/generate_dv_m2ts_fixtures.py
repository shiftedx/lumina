#!/usr/bin/env python3
"""Generate structural dual-PID Dolby Vision Profile 7 M2TS fixtures.

The resulting media is deliberately synthetic and lives outside Git.  It proves
MPEG-TS signalling, PID association, AU timing, and RPU carriage—not display
grading, FEL residual quality, or Blu-ray authoring conformance.

FFmpeg can mux 192-byte M2TS packets and selected PIDs but does not currently
write the Dolby Vision PMT descriptor.  This helper therefore rewrites bounded,
single-packet PMT sections, recomputes their MPEG-2 CRC, and verifies every
signalled field from the generated bytes.  It never tags a base track as Dolby
Vision: only the secondary EL/RPU PID has the DOVI registration and descriptor.
"""
