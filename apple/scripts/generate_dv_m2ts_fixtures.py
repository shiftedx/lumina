M2TS_PACKET_SIZE = 192
M2TS_PREFIX_SIZE = 4
TS_PACKET_SIZE = 188
PAT_PID = 0
HEVC_STREAM_TYPE = 0x24
PRIVATE_PES_STREAM_TYPE = 0x06
REGISTRATION_DESCRIPTOR = b"\x05\x04DOVI"
HEVC_DESCRIPTOR_TAG = 0x38
DOVI_DESCRIPTOR_TAG = 0xB0
COLD_SEEK_DURATION_SECONDS = 96
COLD_SEEK_TARGET_SECONDS = 75
# This is bits per second, as required by FFmpeg's MPEG-TS muxer. It makes the
# optional long fixture large enough that its bounded 4 MiB transport scan ends
# well before the 75-second seek anchor without increasing encoder complexity.
COLD_SEEK_MUX_RATE_BITS_PER_SECOND = 4_000_000


@dataclass(frozen=True)
class Pair:
    """Explicit transport identifiers; validation never relies on adjacency."""

    base_pid: int
    enhancement_pid: int
    audio_pid: int


CONVENTIONAL_PAIR = Pair(0x1011, 0x1015, 0x1100)
NONCONVENTIONAL_PAIR = Pair(0x1029, 0x1073, 0x1141)


@dataclass(frozen=True)
class PMTEntry:
    stream_type: int
    pid: int
    descriptors: bytes


def crc32_mpeg(section: bytes) -> int:
    crc = 0xFFFFFFFF
    for byte in section:
        crc ^= byte << 24
        for _ in range(8):
            crc = (((crc << 1) ^ 0x04C11DB7) if crc & 0x80000000 else crc << 1) & 0xFFFFFFFF
    return crc


def ts_payload(packet: bytes) -> tuple[int, bool, int]:
    """Return PID, PUSI, and the first payload offset in a 188-byte TS packet."""
    if len(packet) != TS_PACKET_SIZE or packet[0] != 0x47:
        raise ValueError("Expected one 188-byte TS packet")
    adaptation = (packet[3] >> 4) & 0x03
    if adaptation == 0:
        raise ValueError("Reserved adaptation-field control")
    offset = 4
    if adaptation in (2, 3):
        offset += 1 + packet[offset]
    if offset > TS_PACKET_SIZE:
        raise ValueError("Truncated adaptation field")
    return ((packet[1] & 0x1F) << 8) | packet[2], bool(packet[1] & 0x40), offset


def m2ts_packets(data: bytes) -> list[bytearray]:
    if len(data) % M2TS_PACKET_SIZE:
        raise ValueError("M2TS payload is not a whole number of 192-byte packets")
    result = []
    for offset in range(0, len(data), M2TS_PACKET_SIZE):
        if data[offset + M2TS_PREFIX_SIZE] != 0x47:
            raise ValueError(f"M2TS sync byte missing at packet {offset // M2TS_PACKET_SIZE}")
        result.append(bytearray(data[offset:offset + M2TS_PACKET_SIZE]))
    return result


def join_packets(packets: list[bytearray]) -> bytes:
    return b"".join(packets)


def psi_section(packet: bytes) -> tuple[int, bytes]:
    """Read a bounded, whole PSI section from a PUSI TS packet."""
    _, pusi, offset = ts_payload(packet)
    if not pusi or offset >= TS_PACKET_SIZE:
        raise ValueError("Expected a payload-unit-start PSI packet")
    pointer = packet[offset]
    start = offset + 1 + pointer
    if start + 3 > TS_PACKET_SIZE:
        raise ValueError("Truncated PSI section header")
    length = 3 + (((packet[start + 1] & 0x0F) << 8) | packet[start + 2])
    if start + length > TS_PACKET_SIZE:
        raise ValueError("Fixture PMT must fit entirely in its initial packet")
    return start, bytes(packet[start:start + length])


def parse_pat(section: bytes) -> list[tuple[int, int]]:
    if not section or section[0] != 0x00 or crc32_mpeg(section) != 0:
        raise ValueError("Invalid PAT")
    section_length = ((section[1] & 0x0F) << 8) | section[2]
    if len(section) != section_length + 3:
        raise ValueError("PAT length mismatch")
    result = []
    for offset in range(8, len(section) - 4, 4):
        program = (section[offset] << 8) | section[offset + 1]
        pid = ((section[offset + 2] & 0x1F) << 8) | section[offset + 3]
        if program:
            result.append((program, pid))
    return result


def parse_pmt(section: bytes) -> tuple[bytes, list[PMTEntry]]:
    if not section or section[0] != 0x02 or crc32_mpeg(section) != 0:
        raise ValueError("Invalid PMT")
    section_length = ((section[1] & 0x0F) << 8) | section[2]
    if len(section) != section_length + 3:
        raise ValueError("PMT length mismatch")
    program_info_length = ((section[10] & 0x0F) << 8) | section[11]
    start = 12 + program_info_length
    if start > len(section) - 4:
        raise ValueError("PMT program-info length exceeds section")
    entries = []
    while start < len(section) - 4:
        stream_type = section[start]
        pid = ((section[start + 1] & 0x1F) << 8) | section[start + 2]
        descriptor_length = ((section[start + 3] & 0x0F) << 8) | section[start + 4]
        end = start + 5 + descriptor_length
        if end > len(section) - 4:
            raise ValueError("PMT ES descriptor length exceeds section")
        entries.append(PMTEntry(stream_type, pid, section[start + 5:end]))
        start = end
    if start != len(section) - 4:
        raise ValueError("PMT stream loop is malformed")
    return section[:12 + program_info_length], entries


def build_pmt(header: bytes, entries: list[PMTEntry], *, version: int | None = None) -> bytes:
    if len(header) < 12 or header[0] != 0x02:
        raise ValueError("Invalid PMT header")
    result = bytearray(header)
    if version is not None:
        result[5] = (result[5] & 0xC1) | ((version & 0x1F) << 1)
    for entry in entries:
        if not 0 <= entry.pid < 0x2000 or len(entry.descriptors) > 0x0FFF:
            raise ValueError("Invalid PMT ES entry")
        result.append(entry.stream_type)
        result.extend((0xE000 | entry.pid).to_bytes(2, "big"))
        result.extend((0xF000 | len(entry.descriptors)).to_bytes(2, "big"))
        result.extend(entry.descriptors)
    section_length = len(result) - 3 + 4
    if section_length > 0x03FF:
        raise ValueError("PMT is too large")
    result[1] = (result[1] & 0xF0) | (section_length >> 8)
    result[2] = section_length & 0xFF
    result.extend(crc32_mpeg(result).to_bytes(4, "big"))
    return bytes(result)


def pmt_locations(packets: list[bytearray]) -> list[tuple[int, int, bytes]]:
    pat_programs: list[tuple[int, int]] | None = None
    for packet in packets:
        pid, pusi, _ = ts_payload(packet[M2TS_PREFIX_SIZE:])
        if pid == PAT_PID and pusi:
            _, section = psi_section(packet[M2TS_PREFIX_SIZE:])
            pat_programs = parse_pat(section)
            break
    if pat_programs is None or len(pat_programs) != 1:
        raise ValueError("Positive M2TS corpus must have exactly one PAT program")
    _, pmt_pid = pat_programs[0]
    locations = []
    for index, packet in enumerate(packets):
        ts = packet[M2TS_PREFIX_SIZE:]
        pid, pusi, _ = ts_payload(ts)
        if pid == pmt_pid and pusi:
            start, section = psi_section(ts)
            locations.append((index, start, section))
    if not locations:
        raise ValueError("PAT PMT PID has no PMT sections")
    return locations


def replace_pmt_sections(
    packets: list[bytearray],
    transform: Callable[[bytes, int], bytes],
) -> None:
    for ordinal, (packet_index, start, section) in enumerate(pmt_locations(packets)):
        fresh = transform(section, ordinal)
        if crc32_mpeg(fresh) != 0:
            raise ValueError("PMT transform did not produce a valid CRC")
        if start + len(fresh) > TS_PACKET_SIZE:
            raise ValueError("Expanded PMT does not fit the bounded PSI packet")
        packet = packets[packet_index]
        begin = M2TS_PREFIX_SIZE + start
        packet[begin:begin + len(fresh)] = fresh
        packet[begin + len(fresh):M2TS_PACKET_SIZE] = b"\xFF" * (M2TS_PACKET_SIZE - begin - len(fresh))


def hvcc_descriptor(mp4: Path) -> bytes:
    """Derive ISO HEVC descriptor 0x38 from the encoded hvcC PTL—not literals."""
    data = mp4.read_bytes()
    for type_offset in range(4, len(data) - 13):
        if data[type_offset:type_offset + 4] != b"hvcC":
            continue
        size = struct.unpack_from(">I", data, type_offset - 4)[0]
        payload = data[type_offset + 4:type_offset - 4 + size]
        if len(payload) >= 13 and payload[0] == 1:
            # hvcC general profile_tier_level fields map directly to the first
            # 12 HEVC_descriptor body bytes.  No temporal subset/still/24-hour
            # indication is present; the remaining five reserved bits are one.
            return bytes([HEVC_DESCRIPTOR_TAG, 13]) + payload[1:13] + b"\x1F"
    raise ValueError(f"No usable hvcC profile_tier_level in {mp4}")


def dovi_descriptor(dependency_pid: int) -> bytes:
    if not 0 <= dependency_pid < 0x2000:
        raise ValueError("DOVI dependency PID is outside the 13-bit range")
    profile_level_flags = (7 << 9) | (6 << 3) | 0b110
    dependency = (dependency_pid << 3) | 0b111
    # Dolby TS v1.2 Table 3-2: v1.0, then P7/L6/RPU+EL/no-BL,
    # dependency PID, compatibility ID 6, and all version-1.0 reserved bits one.
    body = b"\x01\x00" + profile_level_flags.to_bytes(2, "big") + dependency.to_bytes(2, "big") + b"\x6F"
    return bytes([DOVI_DESCRIPTOR_TAG, len(body)]) + body


def descriptors_by_tag(descriptors: bytes) -> list[tuple[int, bytes]]:
    result = []
    offset = 0
    while offset < len(descriptors):
        if offset + 2 > len(descriptors):
            raise ValueError("Truncated descriptor loop")
        tag, length = descriptors[offset], descriptors[offset + 1]
        end = offset + 2 + length
        if end > len(descriptors):
            raise ValueError("Descriptor length exceeds loop")
        result.append((tag, descriptors[offset + 2:end]))
        offset = end
    return result


def parse_dovi_descriptor(descriptors: bytes) -> dict[str, int]:
    candidates = [body for tag, body in descriptors_by_tag(descriptors) if tag == DOVI_DESCRIPTOR_TAG]
    if len(candidates) != 1 or len(candidates[0]) != 7:
        raise ValueError("Expected one seven-byte DOVI descriptor")
    body = candidates[0]
    profile_level_flags = int.from_bytes(body[2:4], "big")
    dependency = int.from_bytes(body[4:6], "big")
    return {
        "versionMajor": body[0],
        "versionMinor": body[1],
        "profile": (profile_level_flags >> 9) & 0x7F,
        "level": (profile_level_flags >> 3) & 0x3F,
        "rpuPresent": (profile_level_flags >> 2) & 1,
        "elPresent": (profile_level_flags >> 1) & 1,
        "blPresent": profile_level_flags & 1,
        "dependencyPid": dependency >> 3,
        "dependencyReserved": dependency & 0x07,
        "compatibilityID": body[6] >> 4,
        "reservedLowNibble": body[6] & 0x0F,
    }


def stream_entries(
    entries: list[PMTEntry],
    pair: Pair,
    base_hevc: bytes,
    el_hevc: bytes,
    *,
    el_first: bool,
    dependency_pid: int | None = None,
    include_dovi: bool = True,
) -> list[PMTEntry]:
    dependency = pair.base_pid if dependency_pid is None else dependency_pid
    result = []
    for entry in entries:
        if entry.pid == pair.base_pid:
            result.append(PMTEntry(HEVC_STREAM_TYPE, entry.pid, base_hevc))
        elif entry.pid == pair.enhancement_pid:
            descriptors = REGISTRATION_DESCRIPTOR + el_hevc
            if include_dovi:
                descriptors += dovi_descriptor(dependency)
            result.append(PMTEntry(PRIVATE_PES_STREAM_TYPE, entry.pid, descriptors))
        else:
            result.append(entry)
    if {entry.pid for entry in result} & {pair.base_pid, pair.enhancement_pid} != {pair.base_pid, pair.enhancement_pid}:
        raise ValueError("PMT did not contain the explicit base/enhancement PIDs")
    if el_first:
        result.sort(key=lambda entry: 0 if entry.pid == pair.enhancement_pid else 1 if entry.pid == pair.base_pid else 2)
    return result


def patch_positive(path: Path, pair: Pair, base_mp4: Path, el_mp4: Path, *, el_first: bool = False) -> dict[str, object]:
    packets = m2ts_packets(path.read_bytes())
    base_hevc = hvcc_descriptor(base_mp4)
    el_hevc = hvcc_descriptor(el_mp4)
    raw_sections = pmt_locations(packets)

    def transform(section: bytes, _: int) -> bytes:
        header, entries = parse_pmt(section)
        return build_pmt(header, stream_entries(entries, pair, base_hevc, el_hevc, el_first=el_first))

    replace_pmt_sections(packets, transform)
    path.write_bytes(join_packets(packets))
    return verify_signalling(path, pair, base_hevc, el_hevc, el_first=el_first, expected_pmt_copies=len(raw_sections))


def verify_signalling(
    path: Path,
    pair: Pair,
    base_hevc: bytes,
    el_hevc: bytes,
    *,
    el_first: bool,
    expected_pmt_copies: int,
) -> dict[str, object]:
    packets = m2ts_packets(path.read_bytes())
    locations = pmt_locations(packets)
    if len(locations) != expected_pmt_copies:
        raise ValueError("PMT copy count changed during patch")
    expected_dovi = {
        "versionMajor": 1, "versionMinor": 0, "profile": 7, "level": 6,
        "rpuPresent": 1, "elPresent": 1, "blPresent": 0,
        "dependencyPid": pair.base_pid, "dependencyReserved": 0b111,
        "compatibilityID": 6, "reservedLowNibble": 0b1111,
    }
    serializations = []
    for _, _, section in locations:
        header, entries = parse_pmt(section)
        entry_by_pid = {entry.pid: entry for entry in entries}
        base = entry_by_pid.get(pair.base_pid)
        enhancement = entry_by_pid.get(pair.enhancement_pid)
        if base != PMTEntry(HEVC_STREAM_TYPE, pair.base_pid, base_hevc):
            raise ValueError("Base PID has an unexpected PMT entry")
        if enhancement is None or enhancement.stream_type != PRIVATE_PES_STREAM_TYPE:
            raise ValueError("EL PID is not private PES as required by DOVI TS")
        tags = descriptors_by_tag(enhancement.descriptors)
        if (0x05, b"DOVI") not in tags or (HEVC_DESCRIPTOR_TAG, el_hevc[2:]) not in tags:
            raise ValueError("EL PID lost its DOVI registration or derived HEVC descriptor")
        if parse_dovi_descriptor(enhancement.descriptors) != expected_dovi:
            raise ValueError("EL DOVI descriptor does not declare the explicit base dependency")
        if el_first and [entry.pid for entry in entries].index(pair.enhancement_pid) > [entry.pid for entry in entries].index(pair.base_pid):
            raise ValueError("PMT declaration order did not put EL before BL")
        serializations.append(section)
    if len(set(serializations)) != 1:
        raise ValueError("PMT copies do not carry identical signalling")
    return {
        "packetBytes": M2TS_PACKET_SIZE,
        "prefixBytes": M2TS_PREFIX_SIZE,
        "pmtCopies": len(locations),
        "basePID": pair.base_pid,
        "enhancementPID": pair.enhancement_pid,
        "audioPID": pair.audio_pid,
        "doviDescriptor": expected_dovi,
        "pmtElFirst": el_first,
    }


def streams(path: Path) -> list[dict[str, object]]:
    return json.loads(run(["ffprobe", "-v", "error", "-show_streams", "-of", "json", str(path)]))["streams"]


def video_ordinal_for_pid(path: Path, pid: int) -> int:
    ordinal = 0
    for stream in streams(path):
        if stream.get("codec_type") == "video":
            stream_pid = int(str(stream["id"]), 0)
            if stream_pid == pid:
                return ordinal
            ordinal += 1
    raise ValueError(f"No video stream with PID 0x{pid:04x}")


def packet_times(path: Path, pid: int) -> list[tuple[int, int]]:
    all_streams = streams(path)
    stream_index = next(index for index, stream in enumerate(all_streams) if int(str(stream["id"]), 0) == pid)
    packets = json.loads(run(["ffprobe", "-v", "error", "-show_packets", "-of", "json", str(path)]))["packets"]
    result = []
    for packet in packets:
        if int(packet.get("stream_index", -1)) != stream_index:
            continue
        if "pts" not in packet or "dts" not in packet:
            raise ValueError("Video PES is missing PTS or DTS")
        result.append((int(packet["pts"]), int(packet["dts"])))
    return result


def keyframe_pts(path: Path, pid: int) -> list[int]:
    all_streams = streams(path)
    stream_index = next(index for index, stream in enumerate(all_streams) if int(str(stream["id"]), 0) == pid)
    frames = json.loads(run(["ffprobe", "-v", "error", "-show_frames", "-of", "json", str(path)]))["frames"]
    result = []
    for frame in frames:
        if int(frame.get("stream_index", -1)) != stream_index or frame.get("key_frame") != 1:
            continue
        timestamp = frame.get("best_effort_timestamp")
        if timestamp is None:
            raise ValueError("Video keyframe has no presentation timestamp")
        result.append(int(timestamp))
    if not result:
        raise ValueError("M2TS base layer has no keyframes")
    return result


def pes_pts_offsets(path: Path, pid: int) -> dict[int, int]:
    """Map unique video PTS values to their M2TS byte offsets."""
    offsets: dict[int, int] = {}
    for index, packet in enumerate(m2ts_packets(path.read_bytes())):
        ts = packet[M2TS_PREFIX_SIZE:]
        actual_pid, pusi, payload_offset = ts_payload(ts)
        payload = ts[payload_offset:]
        if actual_pid != pid or not pusi or len(payload) < 14 or payload[:4] != b"\0\0\1\xe0":
            continue
        if payload[7] >> 6 not in {0b10, 0b11} or payload[8] < 5:
            raise ValueError("Video PES does not carry a bounded PTS header")
        encoded = payload[9:14]
        if len(encoded) != 5 or encoded[0] & 1 != 1 or encoded[2] & 1 != 1 or encoded[4] & 1 != 1:
            raise ValueError("Video PES PTS marker bits are malformed")
        pts = (
            ((encoded[0] >> 1) & 0x07) << 30
            | encoded[1] << 22
            | ((encoded[2] >> 1) & 0x7F) << 15
            | encoded[3] << 7
            | (encoded[4] >> 1)
        )
        if pts in offsets:
            raise ValueError("M2TS video PES repeats a presentation timestamp")
        offsets[pts] = index * M2TS_PACKET_SIZE
    return offsets


def verify_pes_access_units(path: Path, pair: Pair, frames: int) -> None:
    packets = m2ts_packets(path.read_bytes())
    for pid in (pair.base_pid, pair.enhancement_pid):
        starts = []
        for packet in packets:
            ts = packet[M2TS_PREFIX_SIZE:]
            actual_pid, pusi, offset = ts_payload(ts)
            if actual_pid == pid and pusi:
                starts.append(bytes(ts[offset:offset + 4]))
        if len(starts) != frames or any(start != b"\0\0\1\xe0" for start in starts):
            raise ValueError(f"PID 0x{pid:04x} does not have one video PES/AU per generated frame")


def extract_rpus(tool: str, elementary: Path, destination: Path) -> bytes:
    run([tool, "extract-rpu", "-i", str(elementary), "-o", str(destination)])
    return destination.read_bytes()


def expected_output_rpus(temporary: Path, tool: str, enhancement: Path, path: Path, pair: Pair) -> tuple[bytes, bytes]:
    """Return EL decode-order P8.1 RPU units and output BL decode-order units."""
    converted = mode2_rpus(temporary, tool, enhancement)
    units = annexb_units(converted)
    base_times = packet_times(path, pair.base_pid)
    enhancement_times = packet_times(path, pair.enhancement_pid)
    if len(units) != len(enhancement_times):
        raise ValueError("Converted EL RPU count does not match secondary PES count")
    base_pts = [pts for pts, _ in base_times]
    enhancement_pts = [pts for pts, _ in enhancement_times]
    if len(set(base_pts)) != len(base_pts) or set(base_pts) != set(enhancement_pts):
        raise ValueError("Explicit PID pair lacks a one-to-one PTS association")
    by_pts = dict(zip(enhancement_pts, units))
    output = b"".join(by_pts[pts] for pts in base_pts)
    if output == b"".join(units):
        raise ValueError("B-frame fixture did not distinguish BL and EL decode order")
    return b"".join(units), output


def source_pair(
    temporary: Path,
    tool: str,
    source_rpu: bytes,
    *,
    frames: int = FRAMES,
    scene_frames: tuple[int, ...] | None = None,
    base_keyint_frames: int = 24,
    malformed_final_rpu: bool = False,
) -> tuple[Path, Path, Path, bytes]:
    """Build a B-frame BL and presentation-order EL/RPU source pair."""
    base_mp4 = temporary / "base.mp4"
    enhancement = temporary / "enhancement.hevc"
    injected = temporary / "enhancement-rpu.hevc"
    el_mp4 = temporary / "enhancement.mp4"
    rpus = temporary / "p7-source.rpu"
    duration = frames / FRAME_RATE
    encode_timed_layer_mp4(
        base_mp4,
        f"testsrc2=size=128x72:rate={FRAME_RATE}:duration={duration}",
        frames,
        bframes=2,
        keyint=base_keyint_frames,
    )
    encode_layer(enhancement, f"testsrc=size=128x72:rate={FRAME_RATE}:duration={duration}", frames)
    sequence = scene_refreshed_rpus(
        temporary, tool, source_rpu, frames, scene_frames=scene_frames,
    )
    rpus.write_bytes(sequence)
    run([tool, "inject-rpu", "-i", str(enhancement), "--rpu-in", str(rpus), "-o", str(injected)])
    if malformed_final_rpu:
        damaged, _, _ = corrupt_rpu(injected.read_bytes(), frames - 1, frames)
        injected.write_bytes(damaged)
    run(["ffmpeg", "-v", "error", "-y", "-r", str(FRAME_RATE), "-i", str(injected), "-c", "copy", "-tag:v", "hvc1", str(el_mp4)])
    return base_mp4, el_mp4, injected, sequence


def mux_m2ts(
    path: Path,
    base_mp4: Path,
    el_mp4: Path,
    pair: Pair,
    *,
    frames: int = FRAMES,
    el_offset: float = 0,
    mux_rate_bits_per_second: int | None = None,
) -> None:
    command = ["ffmpeg", "-v", "error", "-y", "-copyts", "-i", str(base_mp4)]
    if el_offset:
        command.extend(["-itsoffset", str(el_offset)])
    command.extend(["-i", str(el_mp4), "-f", "lavfi", "-i", f"sine=frequency=440:sample_rate=48000:duration={frames / FRAME_RATE}"])
    command.extend([
        "-map", "0:v:0", "-map", "1:v:0", "-map", "2:a:0", "-c:v", "copy", "-c:a", "aac", "-ac", "2",
        "-shortest", "-muxpreload", "0", "-muxdelay", "0", "-mpegts_copyts", "1", "-mpegts_m2ts_mode", "1",
        "-streamid", f"0:{pair.base_pid}", "-streamid", f"1:{pair.enhancement_pid}", "-streamid", f"2:{pair.audio_pid}",
    ])
    if mux_rate_bits_per_second is not None:
        command.extend(["-muxrate", str(mux_rate_bits_per_second)])
    command.append(str(path))
    run(command)


