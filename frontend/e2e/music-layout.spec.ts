import { mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { expect, test } from '@playwright/test';
import { albumSummary } from '../src/test/galleryFixtures';
import { mockApi, signIn } from './lumina-mock';
import { mockGalleryWall, mockLibrarySections } from './gallery-mock';

test('albums use the artist wall width, show recent items and expose the full catalog', async ({ page }) => {
  await page.setViewportSize({ width: 1800, height: 1000 });
  await mockApi(page, {});
  const requests = await mockGalleryWall(page, { albums: 12, artists: 12 });
  await mockLibrarySections(page, { albums: 12, artists: 12, saved_audio: 13 });
  await page.route('**/api/music/albums/recently-played**', (route) => route.fulfill({ json: { items: Array.from({ length: 6 }, (_, index) => albumSummary(`played-${index}`, { name: `Played ${index}` })) } }));
  await page.goto('/audio');
  await signIn(page);
  const albums = page.locator('.g-music-browse');
  const recent = page.getByRole('region', { name: 'Recently played' });
  await expect(recent.getByRole('button', { name: /^Played 5/ })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'All albums', exact: true })).toBeVisible();
  await expect(page.locator('.g-music-catalog .g-wall')).toBeVisible();
  const albumWidth = (await albums.boundingBox())!.width;
  mkdirSync(join(process.cwd(), '..', 'output', 'music-layout'), { recursive: true });
  await page.screenshot({ path: '../output/music-layout/albums-desktop.png' });
  await page.getByRole('button', { name: 'Artists', exact: true }).click();
  const artists = page.locator('.gallery.g-wall');
  await expect(artists).toBeVisible();
  const artistWidth = (await artists.boundingBox())!.width;
  expect(albumWidth).toBeGreaterThanOrEqual(artistWidth - 1);
  await page.getByRole('button', { name: 'Saved audio' }).click();
  const savedWall = page.locator('.audio-space > .g-still-wall');
  await expect(savedWall).toBeVisible();
  expect((await savedWall.boundingBox())!.width).toBeGreaterThanOrEqual(artistWidth - 1);
  await page.getByRole('button', { name: 'Albums', exact: true }).click();
  const desktopSearch = page.locator('header.g-topbar').getByRole('searchbox', { name: 'Search music' });
  await desktopSearch.fill('lantern');
  await desktopSearch.press('Enter');
  const musicResults = page.getByRole('region', { name: 'Music results for “lantern”' });
  await expect(musicResults).toBeVisible();
  expect((await page.locator('.audio-space > .gallery').boundingBox())!.width).toBeGreaterThanOrEqual(artistWidth - 1);
  await musicResults.getByRole('button', { name: 'Clear' }).click();
  expect(requests.some((url) => url.searchParams.get('type') === 'album' && url.searchParams.get('limit') === '18')).toBe(false);
  await page.locator('.audio-collection-disclosure > summary').click();
  await expect.poll(() => requests.some((url) => url.searchParams.get('type') === 'album' && url.searchParams.get('limit') === '18')).toBe(true);
  await page.locator('.audio-collection-disclosure > summary').click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('region', { name: 'Recently played' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(1);
  const tools = page.getByRole('button', { name: 'Music tools' });
  const savedButton = page.getByRole('button', { name: 'Saved audio' });
  const toolsBox = await tools.boundingBox();
  const savedBox = await savedButton.boundingBox();
  expect(toolsBox && savedBox).toBeTruthy();
  expect(toolsBox!.x >= savedBox!.x + savedBox!.width || savedBox!.x >= toolsBox!.x + toolsBox!.width || toolsBox!.y >= savedBox!.y + savedBox!.height || savedBox!.y >= toolsBox!.y + toolsBox!.height).toBe(true);
  await tools.click();
  const menu = page.getByRole('menu', { name: 'Music tools' });
  await expect(menu.getByRole('menuitem', { name: 'Manage music' })).toBeVisible();
  await expect(menu.getByRole('menuitem', { name: 'Playlists & mixes' })).toBeVisible();
  await expect(menu.getByRole('menuitem', { name: 'Offline listening' })).toBeVisible();
  await page.keyboard.press('Escape');
  await page.screenshot({ path: '../output/music-layout/albums-phone.png' });
  await page.locator('header.g-topbar').getByRole('button', { name: 'Search music' }).click();
  await expect(page.locator('header.g-topbar').getByRole('searchbox', { name: 'Search music' })).toBeFocused();
  await expect(page.locator('main').getByRole('searchbox', { name: 'Search music' })).toHaveCount(0);
  await page.screenshot({ path: '../output/music-layout/search-phone.png' });
  const search = page.locator('header.g-topbar').getByRole('searchbox', { name: 'Search music' });
  await search.fill('lantern');
  await search.press('Enter');
  await expect(page.getByRole('region', { name: 'Music results for “lantern”' })).toBeVisible();
  await expect.poll(() => requests.some((url) => url.pathname === '/api/search' && url.searchParams.get('q') === 'lantern' && url.searchParams.get('scope') === 'music')).toBe(true);
});


test('saved audio and recent albums report errors and recover on retry', async ({ page }) => {
  await mockApi(page, {});
  await mockGalleryWall(page, { albums: 3, artists: 1 });
  await mockLibrarySections(page, { albums: 3, artists: 1, saved_audio: 1 });
  let audioFails = true;
  let recentFails = true;
  await page.route('**/api/library?**', (route) => {
    const url = new URL(route.request().url());
    if (url.searchParams.get('kind') !== 'audio') return route.fallback();
    return audioFails ? route.fulfill({ status: 503, json: { detail: 'unavailable' } }) : route.fulfill({ json: { items: [], next_cursor: null } });
  });
  await page.route('**/api/music/albums/recently-played**', (route) => {
    return recentFails ? route.fulfill({ status: 503, json: { detail: 'unavailable' } }) : route.fulfill({ json: { items: [albumSummary('recovered', { name: 'Recovered album' })] } });
  });
  await page.goto('/audio');
  await signIn(page);
  const saved = page.getByRole('region', { name: 'Saved audio' });
  await expect(saved.getByText('Saved audio could not be loaded.')).toBeVisible();
  await expect(page.getByText(/Some recent albums could not be loaded/)).toBeVisible();
  audioFails = false;
  await saved.getByRole('button', { name: 'Try again' }).click();
  await expect(saved.getByText('No saved audio yet.')).toBeVisible();
  recentFails = false;
  await page.getByRole('alert').filter({ hasText: 'Some recent albums' }).getByRole('button', { name: 'Try again' }).click();
  await expect(page.getByRole('button', { name: /^Recovered album/ })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'All albums', exact: true })).toBeVisible();
});
