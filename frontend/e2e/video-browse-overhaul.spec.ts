import { mkdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, test } from '@playwright/test';
import { mockApi, signIn } from './lumina-mock';
import { mockGalleryWall, mockLibrarySections } from './gallery-mock';
import { mockLibraryItems } from './library-mock';
import { mockLibraryChannels } from './live-youtube-mock';
import { chooseSelect } from './select-helper';

const OUT = fileURLToPath(new URL('../../output/video-browse-overhaul/', import.meta.url));
for (const viewport of [{ name: 'desktop', width: 1440, height: 1000 }, { name: 'phone', width: 390, height: 844 }]) {
  test(`Anime and saved YouTube artwork-led browsing: ${viewport.name}`, async ({ page }) => {
    mkdirSync(OUT, { recursive: true });
    await page.setViewportSize(viewport);
    await page.emulateMedia({ reducedMotion: 'reduce', colorScheme: 'dark' });
    await mockApi(page, { theme: 'dark' }, { categories: ['movies', 'tv', 'anime', 'youtube'], features: { streaming: false, requests: true } });
    const titles = await mockGalleryWall(page, { anime: 12, artwork: true });
    await mockLibrarySections(page);
    await mockLibraryItems(page, { videos: 12 });
    await mockLibraryChannels(page, 4);
    await page.route(/\/api\/library\/[^/]+\/artwork(?:\?|$)/, (route) => route.fulfill({ contentType: 'image/jpeg', body: readFileSync(new URL('./fixtures/open-films/cosmos-backdrop.jpg', import.meta.url)) }));
    await page.goto('/video/anime');
    await signIn(page);
    const anime = page.locator('.g-wall.has-browse-hero .g-browse-hero');
    await expect(anime).toBeVisible();
    await expect(anime.getByRole('button', { name: 'Details' })).toBeVisible();
    const header = await page.locator('header.g-topbar').boundingBox();
    const stage = await anime.boundingBox();
    expect(stage!.y).toBeLessThan(header!.y + header!.height);
    expect(titles.some((url) => url.pathname === '/api/titles' && url.searchParams.get('category') === 'anime' && !url.searchParams.has('type'))).toBe(true);
    await expect(anime.locator('.g-art-image.is-shown').first()).toBeVisible();
    await expect(anime.locator('.hero-frame')).toHaveAttribute('data-hero-revealed', 'true');
    await page.screenshot({ path: join(OUT, `anime-${viewport.name}.png`) });
    if (viewport.name === 'phone') {
      await page.getByRole('button', { name: 'Filters', exact: true }).click();
      await page.getByRole('dialog').getByRole('button', { name: 'Unwatched', exact: true }).click();
      await page.getByRole('dialog').getByRole('button', { name: /^Show/ }).click();
    } else await page.getByRole('button', { name: 'Unwatched', exact: true }).click();
    await expect(page).toHaveURL(/unwatched=1/);
    await expect(page.locator('.g-browse-hero')).toHaveCount(0);
    await page.goto('/video/youtube');
    const video = page.locator('.g-still-wall .g-browse-hero');
    await expect(video.getByRole('heading', { name: 'Video 0' })).toBeVisible();
    await expect(video.getByRole('button', { name: 'Play', exact: true })).toBeVisible();
    const views = page.getByRole('group', { name: 'View', exact: true });
    const videosBox = await views.getByRole('button', { name: 'Videos', exact: true }).boundingBox();
    const channelsBox = await views.getByRole('button', { name: 'Channels', exact: true }).boundingBox();
    expect(Math.abs(videosBox!.y - channelsBox!.y)).toBeLessThan(2);
    const videoBox = await video.boundingBox();
    expect(videoBox!.y).toBeLessThan(header!.y + header!.height);
    await expect(page.getByRole('button', { name: 'Add a link', exact: true })).toHaveCount(0);
    await expect(video.locator('.g-art-image.is-shown').first()).toBeVisible();
    await expect(video.locator('.hero-frame')).toHaveAttribute('data-hero-revealed', 'true');
    await page.screenshot({ path: join(OUT, `youtube-videos-${viewport.name}.png`) });
    await chooseSelect(page, page.getByRole('combobox', { name: 'Source', exact: true }), 'YouTube');
    await expect(page).toHaveURL(/source=youtube/);
    await page.getByRole('group', { name: 'View', exact: true }).getByRole('button', { name: 'Channels', exact: true }).click();
    const channel = page.locator('.g-library-channels .g-browse-hero');
    await expect(channel.getByRole('link', { name: 'Browse', exact: true })).toBeVisible();
    await expect(page.locator('.g-channel-card')).toHaveCount(4);
    await expect(channel.locator('.g-art-image.is-shown').first()).toBeVisible();
    await expect(channel.locator('.hero-frame')).toHaveAttribute('data-hero-revealed', 'true');
    await page.screenshot({ path: join(OUT, `youtube-channels-${viewport.name}.png`) });
    await channel.getByRole('link', { name: 'Browse', exact: true }).click();
    await expect(page).toHaveURL(/\/video\/youtube\?channel=/);
    await expect(page.locator('.g-still-wall .g-browse-hero')).toBeVisible();
  });
}
